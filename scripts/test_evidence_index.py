#!/usr/bin/env python3
"""Generate test-evidence/INDEX.md from the ledger (latest runs per suite, pass-rate trend)."""
import argparse
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import evidence_lib as E  # noqa: E402


def _counts(r):
    if r.get("passed") is None:
        return ""
    return f"{r.get('passed', 0)} passed, {r.get('failed', 0)} failed, {r.get('skipped', 0)} skipped, {r.get('errors', 0)} errors"


def build(root):
    recs = E.read_ledger(root)
    by = collections.OrderedDict()
    for r in recs:
        by.setdefault(r.get("label", "?"), []).append(r)
    out = ["# Test evidence index", "",
           "Generated by `scripts/test_evidence_index.py` from `ledger.jsonl`; do not edit by hand. "
           "Rows marked `backfill` are reconstructions from docs, not original evidence.", "",
           f"Total entries: {len(recs)}. Suites: {len(by)}.", ""]
    for label, rs in sorted(by.items()):
        last20 = rs[-20:]
        rate = 100.0 * sum(1 for r in last20 if r.get("result") == "pass") / len(last20)
        prev20 = rs[-40:-20]
        trend = ""
        if prev20:
            prate = 100.0 * sum(1 for r in prev20 if r.get("result") == "pass") / len(prev20)
            trend = " (earlier 20: %.0f%%, %s)" % (prate, "up" if rate > prate else "down" if rate < prate else "flat")
        out += [f"## {label}", "", f"Runs: {len(rs)}. Pass rate over the last {len(last20)}: {rate:.0f}%{trend}.", "",
                "| When (UTC) | Result | Source | Commit | By | Counts | Log |", "|---|---|---|---|---|---|---|"]
        for r in reversed(rs[-10:]):
            out.append("| {} | {} | {} | {}{} | {} | {} | {} |".format(
                r.get("ts"), r.get("result"), r.get("source"), (r.get("sha") or "")[:7],
                " (dirty)" if r.get("dirty") else "", r.get("by"), _counts(r) or r.get("kind", ""), r.get("log") or "summary only"))
        out.append("")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=E.REPO_ROOT)
    a = ap.parse_args(argv)
    path = os.path.join(E.evidence_dir(a.root), "INDEX.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(build(a.root))
    print("wrote", path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
